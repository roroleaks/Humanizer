/**
 * Scientific Integrity Contracts
 * 
 * Defines immutable protected inventory, discrepancy classification,
 * and scientific validation reporting.
 */

import { DocumentLocation } from './document-section';

/**
 * Severity level assigned to a detected discrepancy between original and revised text.
 * - INFO: Minor stylistic adjustment touching a non-critical term without factual shift.
 * - WARNING: Potential ambiguity or slight drift requiring author review.
 * - FAIL: Absolute integrity violation (altered number, mutated dosage, removed citation, altered conclusion).
 */
export type DiscrepancySeverity = 'INFO' | 'WARNING' | 'FAIL';

/**
 * Categories of sensitive scientific data that must be cataloged in the ProtectedInventory
 * prior to any text refinement.
 */
export type ProtectedItemCategory =
  | 'scientific_terminology'
  | 'medical_terminology'
  | 'drug_name'
  | 'drug_dosage'
  | 'numerical_data'
  | 'statistical_result'
  | 'study_design'
  | 'research_population'
  | 'clinical_outcome'
  | 'citation'
  | 'bibliographic_reference'
  | 'table'
  | 'figure_caption'
  | 'conclusion'
  | 'limitation';

/**
 * Individual protected data entity extracted from the original manuscript.
 */
export interface ProtectedItem {
  id: string;
  category: ProtectedItemCategory;
  originalValue: string;
  location: DocumentLocation;
  notes?: string;
}

/**
 * Immutable catalog of protected scientific elements extracted from a manuscript.
 */
export interface ProtectedInventory {
  manuscriptId: string;
  items: ProtectedItem[];
  createdAt: string; // ISO 8601
}

/**
 * A detected discrepancy between an original protected item and its representation in revised text.
 */
export interface Discrepancy {
  id: string;
  protectedItemId: string;
  originalValue: string;
  revisedValue: string;
  location: DocumentLocation;
  severity: DiscrepancySeverity;
  reason: string;
}

/**
 * Categories evaluated during automated scientific validation checks.
 */
export type ValidationCategory =
  | 'numerical_consistency'
  | 'statistical_consistency'
  | 'terminology_consistency'
  | 'citation_preservation'
  | 'reference_preservation'
  | 'drug_dosage_preservation'
  | 'study_design_consistency'
  | 'clinical_outcome_consistency'
  | 'section_integrity'
  | 'missing_or_duplicated_content';

/**
 * Individual categorical validation check outcome.
 */
export interface ValidationCheck {
  category: ValidationCategory;
  status: 'PASS' | 'WARNING' | 'FAIL';
  detail: string;
}

/**
 * Comprehensive scientific validation report generated by comparing revised text with the protected inventory.
 */
export interface ValidationReport {
  manuscriptId: string;
  status: 'PASS' | 'WARNING' | 'FAIL';
  checks: ValidationCheck[];
  discrepancies: Discrepancy[];
  generatedAt: string; // ISO 8601
}
